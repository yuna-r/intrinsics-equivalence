"""Development generator and executable model for _mm_sub_epi8."""

from ioitf.casepack_families import binary_case


EXAMPLES = (
    ((0x00,) * 16, (0x00,) * 16),
    ((0x80, 0x7F, 0x00, 0xFF) * 4, (0x01, 0xFF, 0x01, 0xFF) * 4),
    ((0x7F, 0x80, 0x40, 0xC0) * 4, (0xFF, 0x01, 0xC0, 0x40) * 4),
    (tuple(range(16)), tuple(reversed(range(16)))),
    ((0x00, 0x01, 0x02, 0x03) * 4, (0x01, 0x02, 0x03, 0x04) * 4),
    ((0xAA, 0x55, 0xCC, 0x33) * 4, (0x55, 0xAA, 0x33, 0xCC) * 4),
)

CASE_ID, MINIMUM_COUNTS, candidates, execute = binary_case(
    "sse2.sub.i8x16.default", "i8x16", "-", EXAMPLES,
    standard=8,
)
